def _bool(value: bool) -> str:
    return "true" if value else "false"


def _q(value: str) -> str:
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')


def _tuple(values: Sequence[str]) -> str:
    if not values:
        return "()"
    if len(values) == 1:
        return "(%s,)" % repr(values[0])
    return repr(tuple(values))


def _swift_array(values: Iterable[str]) -> str:
    return "[" + ", ".join(_q(value) for value in values) + "]"


def render_platform_config(
    grouped: Dict[str, List[Dict[str, Any]]],
) -> str:
    lines = [HEADER, "#pragma once\n\n"]
    for target in ("c3", "c6", "s3", "p4"):
        descriptor = grouped[target][0]
        family = descriptor["family"]
        platform = descriptor["platform"]
        identity = descriptor["identity"]
        lines.append(
            "static constexpr PlatformConfig %s = {\n"
            "    Platform::%s, %s, %s, %s, %s,\n"
            "    %s, %s, %s};\n"
            % (
                PLATFORM_SYMBOLS[target],
                board_descriptor.PLATFORM_ENUM[target],
                _q(identity["chip"]),
                _q(identity["partition"]),
                _bool(platform["use_psram_frame_buffers"]),
                _bool(platform["use_raw_lwip_receive_task"]),
                WIFI_ENUMS[platform["wifi"]],
                IDENTITY_ENUMS[platform["identity_source"]],
                SERIAL_ENUMS[platform["serial"]],
            )
        )
    return "".join(lines)


def render_variants(descriptors: Sequence[Dict[str, Any]]) -> str:
    ordered = sorted(
        descriptors, key=lambda item: item["identity"]["variant_value"])
    lines = [
        HEADER,
        "#pragma once\n\n",
        "enum class Variant : uint8_t {\n",
        "  Unknown = 0,\n",
    ]
    for descriptor in ordered:
        identity = descriptor["identity"]
        lines.append(
            "  %s = %d,\n"
            % (identity["variant"], identity["variant_value"])
        )
    lines.append("};\n\n")
    # Doom is the family's: the validator has required capabilities.doom to
    # equal family.requires_doom_wad, and this reads the family fact.
    doom = [
        "variant == Variant::%s" % item["identity"]["variant"]
        for item in ordered if item["family"]["requires_doom_wad"]
    ]
    lines.append("constexpr bool supportsDoom(Variant variant) {\n")
    lines.append("  return %s;\n" % (" || ".join(doom) if doom else "false"))
    lines.append("}\n")
    audio = [
        "variant == Variant::%s" % item["identity"]["variant"]
        for item in ordered if item["capabilities"]["audio"]
    ]
    lines.append("\nconstexpr bool supportsAudio(Variant variant) {\n")
    lines.append("  return %s;\n" % (" || ".join(audio) if audio else "false"))
    lines.append("}\n")
    return "".join(lines)


def render_touch_calibrations(descriptors: Sequence[Dict[str, Any]]) -> str:
    ordered = sorted(
        descriptors, key=lambda item: item["identity"]["variant_value"])
    lines = [
        HEADER,
        "#pragma once\n\n",
        "struct GeneratedTouchCalibration {\n",
        "  Variant variant;\n",
        "  int16_t panelShort;\n",
        "  int16_t panelLong;\n",
        "  bool rawXMirrored;\n",
        "  bool rawYMirrored;\n",
        "  bool rotateClockwise;\n",
        "};\n\n",
        "static constexpr GeneratedTouchCalibration "
        "GENERATED_TOUCH_CALIBRATIONS[] = {\n",
    ]
    for item in ordered:
        touch = item["touch"]
        lines.append("    {Variant::%s, %d, %d, %s, %s, %s},\n" % (
            item["identity"]["variant"], touch["panel_short"],
            touch["panel_long"], _bool(touch["raw_x_mirrored"]),
            _bool(touch["raw_y_mirrored"]), _bool(touch["rotate_clockwise"])))
    lines.extend([
        "};\n\n",
        "inline const GeneratedTouchCalibration *generatedTouchCalibration(\n",
        "    Variant variant) {\n",
        "  for (const auto &calibration : GENERATED_TOUCH_CALIBRATIONS) {\n",
        "    if (calibration.variant == variant) return &calibration;\n",
        "  }\n",
        "  return nullptr;\n",
        "}\n",
    ])
    return "".join(lines)


def render_usb_host(descriptors: Sequence[Dict[str, Any]]) -> str:
    ordered = sorted(
        descriptors, key=lambda item: item["identity"]["variant_value"])
    lines = [
        HEADER,
        "#pragma once\n\n",
        "struct GeneratedUsbHost {\n",
        "  Variant variant;\n",
        "  bool hostCapable;\n",
        "  bool suppliesVbus;\n",
        "};\n\n",
        "static constexpr GeneratedUsbHost GENERATED_USB_HOSTS[] = {\n",
    ]
    for item in ordered:
        port = board_descriptor.usb_host(item)
        lines.append("    {Variant::%s, %s, %s},\n" % (
            item["identity"]["variant"], _bool(port != "none"),
            _bool(port == "powered")))
    lines.extend([
        "};\n\n",
        "inline const GeneratedUsbHost *generatedUsbHost(Variant variant) {\n",
        "  for (const auto &port : GENERATED_USB_HOSTS) {\n",
        "    if (port.variant == variant) return &port;\n",
        "  }\n",
        "  return nullptr;\n",
        "}\n",
    ])
    return "".join(lines)


def render_identity(descriptors: Sequence[Dict[str, Any]]) -> str:
    ordered = sorted(
        descriptors, key=lambda item: item["identity"]["variant_value"])
    lines = [
        HEADER,
        "#pragma once\n\n",
        "struct GeneratedBoardIdentity {\n",
        "  Variant variant;\n",
        "  Platform platform;\n",
        "  const char *target;\n",
        "  const char *chip;\n",
        "  const char *profile;\n",
        "  const char *partition;\n",
        "};\n\n",
        "static constexpr GeneratedBoardIdentity GENERATED_BOARD_IDENTITIES[] = {\n",
    ]
    def row(descriptor: Dict[str, Any]) -> str:
        identity = descriptor["identity"]
        return (
            "    {Variant::%s, %s, %s, %s, %s, %s},\n"
            % (
                identity["variant"],
                PLATFORM_ENUMS[identity["target"]],
                _q(identity["target"]),
                _q(identity["chip"]),
                _q(identity["profile"]),
                _q(identity["partition"]),
            )
        )
    for descriptor in ordered:
        lines.append(row(descriptor))
    lines.append("};\n\n")
    # The same rows in catalog order, the order users see profiles listed in.
    lines.append(
        "static constexpr GeneratedBoardIdentity "
        "GENERATED_BOARD_IDENTITIES_BY_CATALOG[] = {\n")
    for descriptor in sorted(
            descriptors,
            key=lambda item: (item["identity"]["target"], item["catalog_order"])):
        lines.append(row(descriptor))
    lines.extend([
        "};\n\n",
        "inline const GeneratedBoardIdentity *generatedIdentity(Variant variant) {\n",
        "  for (const auto &identity : GENERATED_BOARD_IDENTITIES) {\n",
        "    if (identity.variant == variant) return &identity;\n",
        "  }\n",
        "  return nullptr;\n",
        "}\n",
    ])
    return "".join(lines)


