def _panel_initializer(descriptor: Dict[str, Any]) -> str:
    panel = descriptor["panel"]
    return (
        "static constexpr PanelConfig %(symbol)s = {\n"
        "    PanelProfile::%(profile)s, PanelDriver::%(driver)s, %(bus)s,\n"
        "    %(width)d, %(height)d, %(memory_width)d, %(memory_height)d,\n"
        "    %(pixel_clock_hz)d, %(spi_mode)d, "
        "%(col_offset)d, %(row_offset)d, %(orientation_offset)d,\n"
        "    %(invert)s, %(round)s, %(rotation)s,\n"
        "    %(dsi_data_lanes)d, %(dsi_lane_mbps)d, "
        "%(hsync_back_porch)d, %(hsync_pulse_width)d, "
        "%(hsync_front_porch)d,\n"
        "    %(vsync_back_porch)d, %(vsync_pulse_width)d, "
        "%(vsync_front_porch)d,\n"
        "    %(window_follows_mirror)s};\n"
        % {
            **panel,
            "bus": PANEL_BUS_ENUMS[panel["bus"]],
            "invert": _bool(panel["invert_color"]),
            "round": _bool(panel["round_display"]),
            "rotation": _bool(panel["supports_command_rotation"]),
            "window_follows_mirror": _bool(
                board_descriptor.window_follows_mirror(descriptor)),
        }
    )


def _config_initializer(descriptor: Dict[str, Any]) -> str:
    identity = descriptor["identity"]
    carrier = descriptor["carrier"]
    touch = descriptor["touch"]
    power = descriptor["power"]
    motion = descriptor["motion"]
    reset = descriptor["reset"]
    backlight = descriptor["backlight"]
    serial = descriptor["serial"]
    values = [
        "Variant::%s" % identity["variant"],
        _q(descriptor["name"]),
        "&%s" % PLATFORM_SYMBOLS[identity["target"]],
        "&%s" % descriptor["panel"]["symbol"],
        *(str(carrier[key]) for key in (
            "pin_sclk", "pin_mosi", "pin_data1", "pin_data2", "pin_data3",
            "pin_cs", "pin_dc", "pin_rst", "pin_bl", "pin_boot",
            "pin_rgb_led")),
        TOUCH_ENUMS[touch["controller"]],
        *(str(touch[key]) for key in ("sda", "scl", "reset", "interrupt")),
        POWER_ENUMS[power["controller"]],
        *(str(power[key]) for key in (
            "battery_adc", "battery_adc_scale", "battery_enable",
            "charge_status")),
        MOTION_ENUMS[motion["controller"]],
        str(motion["x_axis"]),
        str(motion["x_sign"]),
        str(motion["y_axis"]),
        str(motion["y_sign"]),
        str(reset["panel_output"]),
        str(reset["touch_output"]),
        str(backlight["enable_pin"]),
        _bool(backlight["inverted"]),
        str(serial["rx"]),
        str(serial["tx"]),
        *(str(board_descriptor.optional_pin(descriptor, "carrier." + key))
          for key in ("pin_panel_power", "pin_encoder_a", "pin_encoder_b")),
        _bool(descriptor["led"]["channel_order"] == "grb"),
        str(board_descriptor.backlight_floor_permille(descriptor)),
        *(str(board_descriptor.optional_pin(descriptor, "power." + key))
          for key in ("sda", "scl")),
        "0x%02X" % board_descriptor.pmu_panel_aldo_mask(descriptor),
        str(board_descriptor.pmu_input_limit_ma(descriptor)),
        _bool(board_descriptor.boot_button_optional(descriptor)),
        *(str(board_descriptor.optional_pin(descriptor, "motion." + key))
          for key in ("sda", "scl")),
    ]
    rendered = []
    for index in range(0, len(values), 6):
        rendered.append("    " + ", ".join(values[index:index + 6]) + ",\n")
    rendered[-1] = rendered[-1].rstrip(",\n") + "\n"
    return "static constexpr Config %s = {\n%s};\n" % (
        descriptor["migration"]["config_symbol"], "".join(rendered))


def render_configs(descriptors: Sequence[Dict[str, Any]]) -> str:
    generated = [
        descriptor for descriptor in descriptors
        if descriptor["migration"]["firmware_config"] == "generated"
    ]
    lines = [HEADER, "#pragma once\n\n"]
    emitted_panels = set()
    for descriptor in descriptors:
        # Carriers may share one panel profile; the validator has already
        # required every sharer to state identical panel facts.
        symbol = descriptor["panel"]["symbol"]
        if symbol in emitted_panels:
            continue
        emitted_panels.add(symbol)
        lines.append(_panel_initializer(descriptor))
    lines.append("\n")
    for descriptor in generated:
        lines.append(_config_initializer(descriptor))
    return "".join(lines)


def render_config_lookup(descriptors: Sequence[Dict[str, Any]]) -> str:
    ordered = sorted(
        descriptors, key=lambda item: item["identity"]["variant_value"])
    lines = [
        HEADER,
        "#pragma once\n\n",
        "inline const Config *generatedConfigFor(Variant variant) {\n",
        "  switch (variant) {\n",
    ]
    for descriptor in ordered:
        lines.append(
            "    case Variant::%s: return &%s;\n"
            % (
                descriptor["identity"]["variant"],
                descriptor["migration"]["config_symbol"],
            )
        )
    lines.extend([
        "    default: return nullptr;\n",
        "  }\n",
        "}\n",
    ])
    return "".join(lines)


def _physical_probe_key(descriptor: Dict[str, Any]) -> Tuple[Any, ...]:
    detection = descriptor["detection"]
    if detection["sda"] < 0:
        return ()
    return (
        detection["flash_min_exclusive"],
        detection["flash_max_inclusive"],
        detection["sda"],
        detection["scl"],
        detection["frequency_hz"],
        detection["scan_first"],
        detection["scan_last"],
        tuple(detection["addresses"]),
        detection["reset_pin"],
        detection["reset_low_ms"],
        detection["reset_release_wait_ms"],
        detection["release"],
    )


def render_detection(
    grouped: Dict[str, List[Dict[str, Any]]],
) -> str:
    max_probe_count = 0
    max_sense_count = 0
    lines = [
        HEADER,
        "#pragma once\n\n",
        "using namespace boarddetectmodel;\n\n",
    ]
    for target in ("c3", "c6", "s3", "p4"):
        family = sorted(
            grouped[target], key=lambda item: item["detection"]["order"])
        probes: List[Tuple[Any, ...]] = []
        for descriptor in family:
            key = _physical_probe_key(descriptor)
            if key and key not in probes:
                probes.append(key)
        max_probe_count = max(max_probe_count, len(probes))
        amp_pins = board_descriptor.family_amp_enable_pins(family)
        prefix = target.upper()
        if probes:
            lines.append(
                "static constexpr I2cProbePlan GENERATED_%s_PROBES[] = {\n"
                % prefix
            )
            for probe in probes:
                (
                    flash_min, flash_max, sda, scl, frequency, scan_first,
                    scan_last, addresses, reset_pin, reset_low, reset_wait,
                    release,
                ) = probe
                padded = list(addresses) + [0] * (4 - len(addresses))
                quiet = bool({sda, scl, reset_pin} & amp_pins)
                lines.append(
                    "    {%d, %d, %d, %d, %d, %d, %d, "
                    "{%s}, %d, %d, %d, %d, %s, %s},\n"
                    % (
                        flash_min, flash_max, sda, scl, frequency,
                        scan_first, scan_last,
                        ", ".join("0x%02X" % value for value in padded),
                        len(addresses), reset_pin, reset_low, reset_wait,
                        RELEASE_ENUMS[release],
                        "true" if quiet else "false",
                    )
                )
            lines.append("};\n")
        sense_pins: List[int] = []
        for descriptor in family:
            pin = detection_sense(descriptor)[0]
            if pin >= 0 and pin not in sense_pins:
                sense_pins.append(pin)
        max_sense_count = max(max_sense_count, len(sense_pins))
        dsi = [
            item for item in family
            if item["detection"]["kind"] in board_descriptor.DSI_DETECTION_KINDS
        ]
        if dsi:
            # The validator has required every panel-ID candidate to share
            # lanes, reset pin and timings; the slowest lane rate any of the
            # family's panels declares is safe for all of them.
            first = dsi[0]
            lines.append(
                "static constexpr DsiIdProbePlan GENERATED_%s_DSI_ID_PROBE = "
                "{%d, %d, %d, %d, %d};\n"
                % (
                    prefix,
                    first["panel"]["dsi_data_lanes"],
                    min(item["panel"]["dsi_lane_mbps"] for item in dsi),
                    first["detection"]["reset_pin"],
                    first["detection"]["reset_low_ms"],
                    first["detection"]["reset_release_wait_ms"],
                )
            )
        touch_checked = [
            item for item in family if detection_touch_resolution(item)
        ]
        if touch_checked:
            # The validator has required every such candidate to share its
            # touch bus and addresses.
            touch = touch_checked[0]["touch"]
            addresses = list(touch["addresses"])[:2]
            padded = addresses + [0] * (2 - len(addresses))
            lines.append(
                "static constexpr TouchConfigProbePlan "
                "GENERATED_%s_TOUCH_CONFIG_PROBE = {%d, %d, {%s}, %d};\n"
                % (prefix, touch["sda"], touch["scl"],
                   ", ".join("0x%02X" % value for value in padded),
                   len(addresses)))
        if sense_pins:
            lines.append(
                "static constexpr int8_t GENERATED_%s_SENSE_PINS[] = {%s};\n"
                % (prefix, ", ".join("%d" % pin for pin in sense_pins))
            )
        lines.append(
            "static constexpr CandidateRule GENERATED_%s_CANDIDATES[] = {\n"
            % prefix
        )
        for descriptor in family:
            detection = descriptor["detection"]
            probe_key = _physical_probe_key(descriptor)
            probe_index = probes.index(probe_key) if probe_key else 255
            sense_pin, sense_min, sense_max = detection_sense(descriptor)
            sense_suffix = ""
            if sense_pin >= 0:
                sense_suffix = ", %d, %d, %d" % (
                    sense_pins.index(sense_pin), sense_min, sense_max)
            panel_id = detection_panel_id(descriptor)
            touch_resolution = detection_touch_resolution(descriptor)
            if panel_id or touch_resolution:
                if not sense_suffix:
                    sense_suffix = ", NO_SENSE, 0, 0"
                sense_suffix += ", {%s}" % ", ".join(
                    "0x%02X" % value for value in (panel_id or (0, 0, 0)))
            if touch_resolution:
                sense_suffix += ", %d, %d" % touch_resolution
            lines.append(
                "    {%d, %s, %d, %d, %d%s},\n"
                % (
                    descriptor["identity"]["variant_value"],
                    MATCH_ENUMS[detection["kind"]],
                    probe_index,
                    detection["flash_min_exclusive"],
                    detection["flash_max_inclusive"],
                    sense_suffix,
                )
            )
        lines.append("};\n")
        resolution = RESOLUTION_ENUMS[family[0]["detection"]["resolution"]]
        probe_ref = "GENERATED_%s_PROBES" % prefix if probes else "nullptr"
        sense_ref = ""
        if sense_pins:
            sense_ref = ",\n    GENERATED_%s_SENSE_PINS, %d" % (
                prefix, len(sense_pins))
        if dsi or touch_checked:
            if not sense_ref:
                sense_ref = ",\n    nullptr, 0"
            sense_ref += (", &GENERATED_%s_DSI_ID_PROBE" % prefix
                          if dsi else ", nullptr")
        if touch_checked:
            sense_ref += ", &GENERATED_%s_TOUCH_CONFIG_PROBE" % prefix
        lines.append(
            "static constexpr FamilyDetectionPlan GENERATED_%s_DETECTION = {\n"
            "    %s, %d, GENERATED_%s_CANDIDATES,\n"
            "    sizeof(GENERATED_%s_CANDIDATES) / "
            "sizeof(GENERATED_%s_CANDIDATES[0]), %s%s};\n\n"
            % (prefix, probe_ref, len(probes), prefix, prefix, prefix,
               resolution, sense_ref)
        )
    lines.append(
        "static constexpr uint8_t GENERATED_MAX_PROBE_COUNT = %d;\n"
        "static constexpr uint8_t GENERATED_MAX_SENSE_COUNT = %d;\n\n"
        % (max_probe_count, max_sense_count)
    )
    lines.extend([
        "inline const FamilyDetectionPlan &detectionPlanForPlatform(\n",
        "    Platform platform) {\n",
        "  switch (platform) {\n",
        "    case Platform::Esp32C3: return GENERATED_C3_DETECTION;\n",
        "    case Platform::Esp32C6: return GENERATED_C6_DETECTION;\n",
        "    case Platform::Esp32S3: return GENERATED_S3_DETECTION;\n",
        "    default: return GENERATED_P4_DETECTION;\n",
        "  }\n",
        "}\n",
    ])
    return "".join(lines)


def render_p4_compile(grouped: Dict[str, List[Dict[str, Any]]]) -> str:
    descriptor = next(
        item for item in grouped["p4"]
        if item["migration"]["firmware_config"] == "generated")
    selector = descriptor["compile"]["selector"]
    lines = [HEADER, "#pragma once\n\n", "#if defined(%s)\n" % selector]
    for macro in descriptor["compile"]["macros"]:
        lines.append("#define %s 1\n" % macro)
    # One P4 carrier is compile-fixed; more than one are told apart at boot.
    variant = (
        descriptor["identity"]["variant"] if len(grouped["p4"]) == 1
        else "Unknown")
    lines.append(
        "static const Variant COMPILED_VARIANT = Variant::%s;\n" % variant
    )
    lines.append("#endif\n")
    return "".join(lines)


def render_python_catalog(
    grouped: Dict[str, List[Dict[str, Any]]], digest: str,
) -> str:
    lines = [
        "# Generated by tools/generate_board_descriptors.py. Do not edit.\n",
        "SOURCE_SHA256 = %r\n\n" % digest,
        "PLATFORMS = {\n",
    ]
    for target in ("c3", "c6", "s3", "p4"):
        descriptor = grouped[target][0]
        family = descriptor["family"]
        identity = descriptor["identity"]
        lines.append(
            "    %r: dict(key=%r, chip=%r, fqbn=%r, bootloader_address=%d),\n"
            % (
                target, family["platform_key"], identity["chip"],
                family["fqbn"], family["bootloader_address"],
            )
        )
    lines.append("}\n\nBUILD_TARGETS = {\n")
    for target in ("c3", "c6", "s3", "p4"):
        descriptor = grouped[target][0]
        family = descriptor["family"]
        # P4 USB writes still require the operator to name the carrier; the
        # image detects it, but a P4 of unknown wiring must not receive one.
        required_profiles = (
            tuple(item["identity"]["profile"] for item in grouped[target])
            if target in CARRIER_EVIDENCE_FAMILIES else None
        )
        lines.append(
            "    %r: dict(key=%r, platform=%r, partition_csv=%r, "
            "extra_flags=%r, extra_library_dirs=%r, required_profiles=%r, "
            "fqbn_options=%r),\n"
            % (
                family["build_target"], family["build_target"], target,
                family["partition_csv"] or None,
                tuple(family["extra_flags"]),
                tuple(family["extra_library_dirs"]),
                required_profiles,
                tuple(family["fqbn_options"]),
            )
        )
    lines.append("}\n\nFAMILIES = {\n")
    for target in ("c3", "c6", "s3", "p4"):
        descriptor = grouped[target][0]
        family = descriptor["family"]
        profiles = tuple(item["identity"]["profile"] for item in grouped[target])
        hardware = {
            item["identity"]["profile"]: tuple(item["hardware"])
            for item in grouped[target]
        }
        lines.append(
            "    %r: dict(key=%r, platform=%r, build_target=%r, profiles=%r, "
            "flash_sizes=%r, partition_scheme=%r, requires_doom_wad=%r, "
            "hardware=%r, blurb=%r),\n"
            % (
                target, target, target, family["build_target"], profiles,
                tuple(family["flash_bytes"]),
                descriptor["identity"]["partition"],
                family["requires_doom_wad"], hardware, family["blurb"],
            )
        )
    lines.append("}\n\nLEGACY_TARGET_PROFILES = {\n")
    for family in grouped.values():
        for descriptor in family:
            for legacy in descriptor["identity"]["legacy_targets"]:
                lines.append(
                    "    %r: %r,\n"
                    % (legacy, descriptor["identity"]["profile"])
                )
    lines.append("}\n")
    return "".join(lines)


def render_swift_catalog(
    grouped: Dict[str, List[Dict[str, Any]]], digest: str,
) -> str:
    lines = [
        HEADER,
        "import Foundation\n\n",
        "public enum GeneratedBoardCatalog {\n",
        "    public struct Expected: Sendable {\n",
        "        public let chip: String\n",
        "        public let profiles: [String]\n",
        "        public let flashBytes: [Int]\n",
        "        public let partition: String\n",
        "        public let bootloaderAddress: Int\n",
        "    }\n\n",
        "    public static let sourceSHA256 = %s\n" % _q(digest),
        "    public static let requiredFamilies: Set<String> = "
        + _swift_array(("c3", "c6", "s3", "p4")) + "\n",
        "    public static let expected: [String: Expected] = [\n",
    ]
    for target in ("c3", "c6", "s3", "p4"):
        descriptor = grouped[target][0]
        family = descriptor["family"]
        profiles = [
            item["identity"]["profile"] for item in grouped[target]
        ]
        lines.append(
            "        %s: Expected(chip: %s, profiles: %s, flashBytes: %s, "
            "partition: %s, bootloaderAddress: %d),\n"
            % (
                _q(target), _q(descriptor["identity"]["chip"]),
                _swift_array(profiles), repr(family["flash_bytes"]),
                _q(descriptor["identity"]["partition"]),
                family["bootloader_address"],
            )
        )
    lines.append("    ]\n\n")
    lines.append("    public static let profilesByTarget: [String: Set<String>] = [\n")
    for target in ("c3", "c6", "s3", "p4"):
        profiles = [
            item["identity"]["profile"] for item in grouped[target]
        ]
        lines.append(
            "        %s: Set(%s),\n" % (_q(target), _swift_array(profiles))
        )
    for family in grouped.values():
        for descriptor in family:
            for legacy in descriptor["identity"]["legacy_targets"]:
                lines.append(
                    "        %s: Set([%s]),\n"
                    % (_q(legacy), _q(descriptor["identity"]["profile"]))
                )
    lines.append("    ]\n\n")
    lines.append("    public static let geometryByProfile: [String: PanelGeometry] = [\n")
    for target in ("c3", "c6", "s3", "p4"):
        for descriptor in grouped[target]:
            profile = descriptor["identity"]["profile"]
            panel = descriptor["panel"]
            lines.append(
                "        %s: PanelGeometry(width: %d, height: %d),\n"
                % (_q(profile), panel["width"], panel["height"])
            )
    lines.append("    ]\n\n")
    # The descriptor's own name, which is what the app shows as the board
    # model: "ESP32-C6-LCD-1.47 (ST7789)" rather than the profile token.
    lines.append("    public static let boardNameByProfile: [String: String] = [\n")
    for target in ("c3", "c6", "s3", "p4"):
        for descriptor in grouped[target]:
            lines.append(
                "        %s: %s,\n"
                % (_q(descriptor["identity"]["profile"]), _q(descriptor["name"]))
            )
    lines.append("    ]\n\n")
    lines.append("    public static let universalFamilyAliases: [String: Set<String>] = [\n")
    for target in ("c3", "c6", "s3", "p4"):
        aliases = {target}
        for descriptor in grouped[target]:
            aliases.update(descriptor["identity"]["legacy_targets"])
        lines.append(
            "        %s: Set(%s),\n"
            % (_q(target), _swift_array(sorted(aliases)))
        )
    lines.append("    ]\n\n")
    quarter_turns = [
        descriptor["identity"]["profile"]
        for family in grouped.values()
        for descriptor in family
        if 1 in descriptor["orientation"]["quarter_turns"]
    ]
    lines.append(
        "    public static let quarterTurnProfiles: Set<String> = Set(%s)\n\n"
        % _swift_array(quarter_turns)
    )
    # Boards with a knob (encoder lines on the carrier). The knob drives the
    # Mac's volume and mute through media keys whatever the touch preset, so
    # the app offers the Accessibility grant on these boards' pages.
    encoders = [
        descriptor["identity"]["profile"]
        for family in grouped.values()
        for descriptor in family
        if board_descriptor.optional_pin(descriptor, "carrier.pin_encoder_a") >= 0
        and board_descriptor.optional_pin(descriptor, "carrier.pin_encoder_b") >= 0
    ]
    lines.append(
        "    public static let encoderProfiles: Set<String> = Set(%s)\n\n"
        % _swift_array(encoders))
    # Families whose USB writes need the operator to name the carrier, the
    # same rule espdisp.py applies through required_profiles.
    lines.append(
        "    public static let carrierEvidenceFamilies: Set<String> = Set(%s)\n\n"
        % _swift_array(CARRIER_EVIDENCE_FAMILIES))
    # Panels the app may stream over ETL1: the large-tile families' glass
    # that no band row can carry.
    large = []
    for target in LARGE_TILE_FAMILIES:
        for descriptor in grouped[target]:
            size = (descriptor["panel"]["width"], descriptor["panel"]["height"])
            if size not in large:
                large.append(size)
    lines.append(
        "    public static let largeTileGeometries: Set<PanelGeometry> = [%s]\n\n"
        % ", ".join("PanelGeometry(width: %d, height: %d)" % size
                    for size in sorted(large)))
    lines.append("    public static let hardwareByProfile: [String: [String]] = [\n")
    for target in ("c3", "c6", "s3", "p4"):
        for descriptor in grouped[target]:
            lines.append(
                "        %s: %s,\n"
                % (_q(descriptor["identity"]["profile"]),
                   _swift_array(descriptor["hardware"])))
    lines.append("    ]\n")
    lines.append("}\n")
    return "".join(lines)


def expected_outputs(repo_root: str) -> Dict[str, str]:
    descriptors = list(board_descriptor.validate_descriptors(
        board_descriptor.load_repository_descriptors(repo_root)))
    grouped = board_descriptor.grouped_by_family(descriptors)
    required_families = {"c3", "c6", "s3", "p4"}
    if set(grouped) != required_families:
        raise board_descriptor.DescriptorError(
            "descriptor repository must contain exactly c3, c6, s3, and p4; found %s"
            % ", ".join(sorted(grouped))
        )
    digest = board_descriptor.descriptor_source_digest(repo_root)
    return {
        "firmware/libraries/espdisp_board/src/generated_platform_config.h":
            render_platform_config(grouped),
        "firmware/libraries/espdisp_board/src/generated_board_variants.h":
            render_variants(descriptors),
        "firmware/libraries/espdisp_board/src/generated_board_identity.h":
            render_identity(descriptors),
        "firmware/libraries/espdisp_board/src/generated_board_audio.h":
            render_audio(descriptors),
        "firmware/libraries/espdisp_board/src/generated_board_touch.h":
            render_touch_calibrations(descriptors),
        "firmware/libraries/espdisp_board/src/generated_board_usb_host.h":
            render_usb_host(descriptors),
        "firmware/libraries/espdisp_board/src/generated_board_configs.h":
            render_configs(descriptors),
        "firmware/libraries/espdisp_board/src/generated_board_config_lookup.h":
            render_config_lookup(descriptors),
        "firmware/libraries/espdisp_board/src/generated_board_detection.h":
            render_detection(grouped),
        "firmware/libraries/espdisp_board/src/generated_p4_compile.h":
            render_p4_compile(grouped),
        "tools/generated_board_catalog.py":
            render_python_catalog(grouped, digest),
        "mac/ESPDisplaySender/Sources/SenderProtocol/GeneratedBoardCatalog.swift":
            render_swift_catalog(grouped, digest),
    }


def write_outputs(repo_root: str, check: bool) -> bool:
    stale = []
    for relative, content in expected_outputs(repo_root).items():
        path = pathlib.Path(repo_root) / relative
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(relative)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale and check:
        print(
            "generated board files are stale: %s; run "
            "python3 tools/generate_board_descriptors.py"
            % ", ".join(stale),
            file=sys.stderr,
        )
        return False
    if not check:
        for relative in stale:
            print("generated %s" % relative)
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    try:
        return 0 if write_outputs(repo_root, args.check) else 1
    except board_descriptor.DescriptorError as exc:
        print("board descriptor error: %s" % exc, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
