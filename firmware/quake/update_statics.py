#!/usr/bin/env python3
"""Regenerate src/platform/quake_statics_lists.h from the compiled engine.

Every zero-initialised file-scope array or struct the engine defines that is at
least MIN_BYTES long is moved out of internal RAM (see quake_statics.h for
how). This reads the symbol table of the engine units as they compile now --
objects built with the P4 toolchain, one per engine_units/qe_*.c -- and writes
the per-unit lists and renames:

    python3 firmware/quake/update_statics.py <directory of qe_*.o>

Already-relocated names show up as their 4-byte quake_<name> pointer and are
kept. Smaller globals stay where they are: below MIN_BYTES a pointer saves
little and costs an indirection on every use, and the 12- and 16-byte ones are
mostly vec3_t the renderer reads per vertex.

EXCLUDED names are never relocated, each for a reason given beside it. After
regenerating, the cross-compile must stay free of -Wshadow warnings on any
relocated name (a local of the same name would be renamed too), and
firmware/test/test_quake_statics.sh must pass.
"""
import os
import re
import subprocess
import sys

MIN_BYTES = 20

# Units whose arrays the renderer touches per span, edge or vertex: allocated
# from internal RAM at Quake start (WiFi and streaming are off then, so it has
# room), falling back to PSRAM.
INTERNAL_UNIT_PREFIXES = ("d_", "r_")
INTERNAL_NAMES = {"localstack", "pr_stack"}  # the QuakeC interpreter's stacks

EXCLUDED = {
    # Generic names also used for locals and parameters (cl_main.c's and
    # in_null.c's `usercmd_t *cmd`, r_aclip.c's `finalvert_t *fv` and
    # r_alias.c's `auxvert_t *av`).
    "av",
    "cmd",
    "fv",
    # Used in file-scope initialisers (d_polyse.c), which must be constant.
    "r_p0",
    "r_p1",
    "r_p2",
}

NM = os.path.expanduser(
    "~/Library/Arduino15/packages/esp32/tools/esp-rv32/2601/bin/riscv32-esp-elf-nm")

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "src", "platform", "quake_statics_lists.h")


def unit_symbols(obj):
    out = subprocess.run([NM, "-S", "-t", "d", obj], check=True,
                         capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 4:
            yield int(parts[1]), parts[2], parts[3]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    objdir = sys.argv[1]
    units = {}
    for name in sorted(os.listdir(objdir)):
        m = re.match(r"qe_(\w+)\.o$", name)
        if not m:
            continue
        unit = m.group(1)
        names = set()
        for size, kind, symbol in unit_symbols(os.path.join(objdir, name)):
            if kind not in "bBsS" or "." in symbol:
                continue
            if symbol.startswith("quake_"):
                # Relocated already (a pointer), or one of the renames in
                # quake_renames.h, which are ordinary globals.
                base = symbol[len("quake_"):]
                if (size == 4 and kind in "bB" and base not in RENAMED
                        and base not in EXCLUDED):
                    names.add(base)
                continue
            if size >= MIN_BYTES and symbol not in EXCLUDED:
                names.add(symbol)
        if names:
            units[unit] = sorted(names)

    lines = [
        "// Generated by firmware/quake/update_statics.py; do not edit. The",
        "// engine arrays moved out of internal RAM, per defining unit, and their",
        "// renames. See quake_statics.h for how and why.",
        "#pragma once",
        "",
    ]
    for unit, names in units.items():
        lines.append("#define QUAKE_STATICS_%s(X) \\" % unit)
        for i, n in enumerate(names):
            where = ("INTERNAL" if unit.startswith(INTERNAL_UNIT_PREFIXES)
                     or n in INTERNAL_NAMES else "PSRAM")
            tail = " \\" if i + 1 < len(names) else ""
            lines.append("  X(%s, %s)%s" % (n, where, tail))
    lines.append("")
    lines.append("#define QUAKE_STATICS_UNITS(X) \\")
    for i, unit in enumerate(units):
        tail = " \\" if i + 1 < len(units) else ""
        lines.append("  X(%s)%s" % (unit, tail))
    lines.append("")
    for unit, names in units.items():
        for n in names:
            lines.append("#define %s (*quake_%s)" % (n, n))
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    total = sum(len(v) for v in units.values())
    print("%d relocated names in %d units -> %s" % (total, len(units), OUT))


def renamed_globals():
    path = os.path.join(HERE, "src", "platform", "quake_renames.h")
    return {m for m in re.findall(r"^#define \w+ quake_(\w+)",
                                  open(path).read(), re.M)}


RENAMED = renamed_globals()

if __name__ == "__main__":
    main()
